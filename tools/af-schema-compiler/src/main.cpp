#include "generator.hpp"
#include "schema_model.hpp"

#include <nlohmann/json.hpp>

#include <filesystem>
#include <fstream>
#include <iostream>
#include <string>

namespace fs = std::filesystem;

static fs::path repoRootFromArgv(int argc, char** argv) {
    if (argc >= 2) {
        return fs::absolute(argv[1]);
    }
    return fs::absolute(fs::path(__FILE__).parent_path().parent_path().parent_path().parent_path());
}

int main(int argc, char** argv) {
    const fs::path repoRoot = repoRootFromArgv(argc, argv);
    const fs::path schemaPath = repoRoot / "schema/appsflyer-plugins-rpc-schema.json";
    const fs::path outDir = repoRoot / "Classes/AppsFlyer/generated";

    std::ifstream in(schemaPath);
    if (!in) {
        std::cerr << "Failed to open schema: " << schemaPath << "\n";
        return 1;
    }

    nlohmann::json schema;
    try {
        in >> schema;
    } catch (const std::exception& ex) {
        std::cerr << "Schema parse error: " << ex.what() << "\n";
        return 1;
    }

    const auto methods = afcodegen::loadEligibleMethods(schema);
    const auto files = afcodegen::generateAll(methods);

    std::error_code ec;
    fs::create_directories(outDir, ec);

    for (const auto& entry : files) {
        const fs::path outPath = outDir / entry.first;
        std::ofstream out(outPath);
        if (!out) {
            std::cerr << "Failed to write: " << outPath << "\n";
            return 1;
        }
        out << entry.second;
        std::cout << "Wrote " << fs::relative(outPath, repoRoot) << " (" << methods.size()
                  << " methods)\n";
    }

    const fs::path pluginVersionPath = repoRoot / "version/plugin-version.json";
    std::ifstream versionIn(pluginVersionPath);
    if (!versionIn) {
        std::cerr << "Failed to open: " << pluginVersionPath << "\n";
        return 1;
    }
    nlohmann::json pluginVersionDoc;
    try {
        versionIn >> pluginVersionDoc;
    } catch (const std::exception& ex) {
        std::cerr << "plugin-version.json parse error: " << ex.what() << "\n";
        return 1;
    }
  const std::string pluginId = pluginVersionDoc.value("plugin", "cocos2dx");
    const std::string pluginVersion = pluginVersionDoc.value("pluginVersion", "");
    if (pluginVersion.empty()) {
        std::cerr << "plugin-version.json: missing pluginVersion\n";
        return 1;
    }

    const fs::path metadataPath = outDir / "AppsFlyerPluginMetadata.generated.h";
    std::ofstream metadataOut(metadataPath);
    if (!metadataOut) {
        std::cerr << "Failed to write: " << metadataPath << "\n";
        return 1;
    }
    metadataOut << "// Auto-generated by tools/af-schema-compiler from version/plugin-version.json — "
                   "do not edit.\n";
    metadataOut << "#ifndef AppsFlyerPluginMetadata_generated_h\n";
    metadataOut << "#define AppsFlyerPluginMetadata_generated_h\n\n";
    metadataOut << "namespace appsflyer {\n";
    metadataOut << "inline constexpr const char kAppsFlyerPluginId[] = \"" << pluginId << "\";\n";
    metadataOut << "inline constexpr const char kAppsFlyerPluginVersion[] = \"" << pluginVersion
                << "\";\n";
    metadataOut << "} // namespace appsflyer\n\n";
    metadataOut << "#endif\n";
    std::cout << "Wrote " << fs::relative(metadataPath, repoRoot) << "\n";

    const fs::path legacyXCpp = outDir / "AppsFlyerX.generated.cpp";
    if (fs::exists(legacyXCpp)) {
        fs::remove(legacyXCpp, ec);
        if (!ec) {
            std::cout << "Removed stale " << fs::relative(legacyXCpp, repoRoot) << "\n";
        }
    }
    for (const char* stale : {"AppsFlyerRpcValueMaps.generated.h", "AppsFlyerRpcValueMaps.generated.cpp"}) {
        const fs::path stalePath = outDir / stale;
        if (fs::exists(stalePath)) {
            fs::remove(stalePath, ec);
            if (!ec) {
                std::cout << "Removed stale " << fs::relative(stalePath, repoRoot) << "\n";
            }
        }
    }

    return 0;
}
